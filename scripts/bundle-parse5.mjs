// Bundle parse5 (and its only dependency, entities) into one ESM file that runs
// unchanged in the browser and in Node. The output is committed as
// vendor/parse5.js so the editor never loads code from a CDN at runtime.
// tests/unit/vendor.test.mjs rebuilds it into a temporary directory and fails if
// the committed file differs, so a dependency bump is always a visible diff.
import { build } from "esbuild";
import { copyFile, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function packageVersion(name) {
  const manifest = JSON.parse(await readFile(path.join(root, "node_modules", name, "package.json"), "utf8"));
  return manifest.version;
}

export async function bundleParse5({ outfile = path.join(root, "vendor", "parse5.js") } = {}) {
  const versions = {
    parse5: await packageVersion("parse5"),
    entities: await packageVersion("entities"),
    esbuild: await packageVersion("esbuild"),
  };

  await build({
    entryPoints: [path.join(root, "vendor", "parse5-entry.js")],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: ["es2022"],
    minify: false,
    legalComments: "inline",
    outfile,
    banner: {
      js: [
        `// parse5 ${versions.parse5} + entities ${versions.entities}, bundled with esbuild ${versions.esbuild}.`,
        "// Generated by scripts/bundle-parse5.mjs (npm run vendor). Do not edit by hand.",
        "// parse5: MIT licence (vendor/parse5.LICENSE). entities: BSD-2-Clause (vendor/entities.LICENSE).",
      ].join("\n"),
    },
    logLevel: "warning",
  });

  return versions;
}

if (path.resolve(process.argv[1] || "") === fileURLToPath(import.meta.url)) {
  const versions = await bundleParse5();
  await copyFile(path.join(root, "node_modules/parse5/LICENSE"), path.join(root, "vendor/parse5.LICENSE"));
  await copyFile(path.join(root, "node_modules/entities/LICENSE"), path.join(root, "vendor/entities.LICENSE"));
  console.log(`Bundled parse5 ${versions.parse5} with entities ${versions.entities} into vendor/parse5.js`);
}
